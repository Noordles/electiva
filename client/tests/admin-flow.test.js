import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import { chromium, expect } from '@playwright/test';
import { apiFixture } from '../../server/tests/api-helpers.js';
import { directorySimulator } from '../../tools/directory-simulator.js';
import { startServer } from '../../server/src/server.js';

test('production admin: course, offering, stale edit, promotion, report, archive and HTTP import', { timeout: 90000 }, async t => {
  let fault = 'none';
  const provider = await startServer(directorySimulator({ fault: () => fault })); t.after(() => provider.close());
  const { db, running, accounts, login, request } = await apiFixture(t, { staticDirectory: path.resolve('client/dist'), directory: { baseUrl: provider.url } });
  const browser = await chromium.launch(); t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } }), page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(running.url + '/login');
  await page.getByLabel('Account email').fill('admin@example.test'); await page.getByLabel('Password', { exact: true }).fill(accounts.password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Course library', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New course' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Course code').fill('JIN-UX'); await dialog.getByLabel('Course title').fill('Designing Accessible Choices');
  await dialog.getByLabel('Description', { exact: true }).fill('Practical accessible interfaces and clear enrollment decisions.');
  await dialog.getByLabel('Department').fill('Design'); await dialog.getByRole('button', { name: 'Create course', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.getByLabel('Find a course').fill('JIN-UX');
  const row = page.getByRole('row').filter({ hasText: 'JIN-UX' }); await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByLabel('Credits', { exact: true }).fill('6'); await dialog.getByRole('button', { name: 'Save course' }).click();
  await expect(row).toContainText('6');
  await row.getByRole('button', { name: 'Create offering' }).click();
  await dialog.getByLabel('Capacity', { exact: true }).fill('1');
  const local = value => { const d = new Date(value); return new Date(d.getTime() - d.getTimezoneOffset() * 60000).toISOString().slice(0, 16); };
  await dialog.getByLabel('Enrollment opens (local time)').fill(local(Date.now() - 600000));
  await dialog.getByLabel('Enrollment closes (local time)').fill(local(Date.now() + 3600000));
  await dialog.getByRole('button', { name: 'Create draft' }).click(); await expect(dialog).toHaveCount(0);
  await page.getByRole('link', { name: 'Offerings', exact: true }).click();
  let offering = page.locator('.offering-row').filter({ hasText: 'JIN-UX' }); await expect(offering).toContainText('DRAFT');
  await offering.getByRole('button', { name: 'Publish', exact: true }).click(); await dialog.getByRole('button', { name: 'Publish offering' }).click();
  await expect(offering).toContainText('PUBLISHED');
  const [{ id: oid }] = await db.all("SELECT o.id FROM offerings o JOIN courses c ON c.id=o.courseId WHERE c.code='JIN-UX'");
  const students = await Promise.all(['student1@example.test', 'student2@example.test'].map(email => login(email)));
  for (const session of students) assert.equal((await request(`/offerings/${oid}/enrollments`, { session, method: 'POST', body: {} })).status, 201);
  await page.reload(); await expect(offering).toContainText('1 / 1');
  await offering.getByRole('button', { name: 'View roster' }).click();
  await expect(dialog.getByRole('table')).toContainText('WAITLISTED');
  await dialog.getByLabel('Roster status').selectOption('ACTIVE'); await expect(dialog.getByRole('table')).not.toContainText('WAITLISTED');
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await offering.getByRole('button', { name: 'Edit offering' }).click(); await dialog.getByLabel('Capacity', { exact: true }).fill('2');
  const admin = await login('admin@example.test');
  assert.equal((await request(`/admin/offerings/${oid}`, { session: admin, method: 'PATCH', body: { version: 2, term: '2026-2027' } })).status, 200);
  await dialog.getByRole('button', { name: 'Save offering' }).click();
  await expect(dialog.getByRole('alert')).toContainText('changed');
  await dialog.getByRole('button', { name: 'Back', exact: true }).click();
  await offering.getByRole('button', { name: 'Edit offering' }).click(); await expect(dialog.getByText('Editing version 3.', { exact: false })).toBeVisible();
  await dialog.getByLabel('Capacity', { exact: true }).fill('2'); await dialog.getByRole('button', { name: 'Save offering' }).click();
  await expect(offering).toContainText('2 / 2');
  await offering.getByRole('button', { name: 'Archive', exact: true }).click(); await dialog.getByRole('button', { name: 'Archive offering' }).click();
  await expect(dialog.getByRole('alert')).toContainText('Cancel current memberships');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  for (const session of students) {
    const own = (await request('/me/enrollments', { session })).body.data.find(item => item.offeringId === oid);
    assert.equal(own.status, 'ACTIVE');
    assert.equal((await request(`/me/enrollments/${own.id}/cancel`, { session, method: 'POST', body: {} })).status, 200);
  }
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  const report = page.getByRole('row').filter({ hasText: 'JIN-UX' }); await expect(report).toHaveCount(1);
  assert.deepEqual(await report.locator('td').allTextContents().then(values => values.slice(1)), ['2', '0', '0', '2']);
  await page.getByRole('link', { name: 'Offerings', exact: true }).click(); await offering.getByRole('button', { name: 'Archive', exact: true }).click();
  await dialog.getByRole('button', { name: 'Archive offering' }).click(); await expect(offering).toContainText('ARCHIVED');
  await page.getByRole('link', { name: 'Directory', exact: true }).click();
  await page.getByLabel('Directory course code').fill('EXT-DATA'); await page.getByRole('button', { name: 'Look up course' }).click();
  await expect(page.getByRole('heading', { name: 'Data Storytelling' })).toBeVisible();
  await page.getByRole('button', { name: 'Import to course library' }).click(); await expect(page.getByRole('status')).toContainText('was saved');
  await page.getByRole('button', { name: 'Import to course library' }).click();
  assert.equal((await db.all("SELECT count(*) AS n FROM courses WHERE externalCode='EXT-DATA'"))[0].n, 1);
  fault = 'error'; await page.getByLabel('Directory course code').fill('EXT-WEB'); await page.getByRole('button', { name: 'Look up course' }).click();
  await expect(page.getByRole('alert')).toContainText('unavailable');
  fault = 'none'; await page.getByRole('button', { name: 'Look up course' }).click(); await expect(page.getByRole('heading', { name: 'Accessible Web Interfaces' })).toBeVisible();
  await page.getByRole('link', { name: 'Offerings', exact: true }).click();
  await mkdir('artifacts/m3', { recursive: true });
  for (const width of [1280, 768, 360]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `admin overflow at ${width}`);
    await page.screenshot({ path: `artifacts/m3/admin-${width}.png`, fullPage: true });
  }
  for (const section of ['Courses', 'Reports', 'Directory']) {
    await page.getByRole('link', { name: section, exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `${section} overflow at 360`);
  }
  assert.deepEqual(errors, []);
});
